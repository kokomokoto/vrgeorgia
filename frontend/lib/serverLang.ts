import { headers } from 'next/headers';
import {
  DEFAULT_SITE_LANG,
  SITE_LANG_HEADER,
  normalizeSiteLang,
  type SiteLang,
} from '@/lib/siteLang';

/**
 * Language of the current request, as resolved by the middleware
 * (URL prefix → cookie → default). Server components / generateMetadata only.
 */
export async function getRequestLang(): Promise<SiteLang> {
  try {
    const h = await headers();
    return normalizeSiteLang(h.get(SITE_LANG_HEADER)) ?? DEFAULT_SITE_LANG;
  } catch {
    return DEFAULT_SITE_LANG;
  }
}

/** Un-prefixed pathname of the current request (set by middleware). */
export async function getRequestPathname(): Promise<string> {
  try {
    const h = await headers();
    return h.get('x-pathname') || '/';
  } catch {
    return '/';
  }
}

/** CSP nonce generated by the middleware for this request. */
export async function getRequestNonce(): Promise<string | undefined> {
  try {
    const h = await headers();
    return h.get('x-nonce') || undefined;
  } catch {
    return undefined;
  }
}

type LocaleBundle = Record<string, string>;

/**
 * Translation bundle for a non-default language, loaded server-side only so the
 * client bundle keeps EN/RU as lazy chunks. Georgian is bundled statically.
 */
export async function loadLocaleBundleServer(lang: SiteLang): Promise<LocaleBundle | null> {
  if (lang === 'en') {
    const mod = await import('@/lib/locales/en');
    return mod.default as unknown as LocaleBundle;
  }
  if (lang === 'ru') {
    const mod = await import('@/lib/locales/ru');
    return mod.default as unknown as LocaleBundle;
  }
  return null;
}
